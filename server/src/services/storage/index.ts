import fs from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';
import { env } from '../../config/env';

export interface StorageAdapter {
  readonly driver: 'local' | 's3';
  put(key: string, data: Buffer, mimeType: string): Promise<void>;
  get(key: string): Promise<Readable>;
  delete(key: string): Promise<void>;
}

/** Local-disk adapter: the default, so the app is fully usable without any cloud storage. */
class LocalStorage implements StorageAdapter {
  readonly driver = 'local' as const;
  private root = path.resolve(env.UPLOAD_DIR);

  private resolve(key: string): string {
    // Keys are generated by the server, but guard against traversal anyway.
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep)) throw new Error('Invalid storage key');
    return full;
  }
  async put(key: string, data: Buffer): Promise<void> {
    const full = this.resolve(key);
    await fs.mkdir(path.dirname(full), { recursive: true });
    await fs.writeFile(full, data, { mode: 0o640 });
  }
  async get(key: string): Promise<Readable> {
    const handle = await fs.open(this.resolve(key), 'r');
    return handle.createReadStream();
  }
  async delete(key: string): Promise<void> {
    await fs.rm(this.resolve(key), { force: true });
  }
}

/** S3-compatible adapter (AWS S3, MinIO, R2, …). Loaded lazily so local-only setups never touch the SDK. */
class S3Storage implements StorageAdapter {
  readonly driver = 's3' as const;
  private clientPromise = import('@aws-sdk/client-s3').then((sdk) => ({
    sdk,
    client: new sdk.S3Client({
      region: env.S3_REGION,
      endpoint: env.S3_ENDPOINT,
      forcePathStyle: env.S3_FORCE_PATH_STYLE,
      credentials: { accessKeyId: env.S3_ACCESS_KEY_ID as string, secretAccessKey: env.S3_SECRET_ACCESS_KEY as string },
    }),
  }));

  async put(key: string, data: Buffer, mimeType: string): Promise<void> {
    const { sdk, client } = await this.clientPromise;
    await client.send(
      new sdk.PutObjectCommand({ Bucket: env.S3_BUCKET, Key: key, Body: data, ContentType: mimeType, ServerSideEncryption: undefined }),
    );
  }
  async get(key: string): Promise<Readable> {
    const { sdk, client } = await this.clientPromise;
    const out = await client.send(new sdk.GetObjectCommand({ Bucket: env.S3_BUCKET, Key: key }));
    return out.Body as Readable;
  }
  async delete(key: string): Promise<void> {
    const { sdk, client } = await this.clientPromise;
    await client.send(new sdk.DeleteObjectCommand({ Bucket: env.S3_BUCKET, Key: key }));
  }
}

let storage: StorageAdapter | null = null;
export function getStorage(): StorageAdapter {
  storage ??= env.STORAGE_DRIVER === 's3' ? new S3Storage() : new LocalStorage();
  return storage;
}
export function setStorageForTests(s: StorageAdapter | null): void {
  storage = s;
}
